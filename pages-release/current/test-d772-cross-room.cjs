'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(process.argv[2]||'current-site');
const state={activeCourse:'D772',progress:{D772:{},D755:{},D756:{}}};
let saves=0;
const ctx={S:state,window:{S:state,save(){saves++}},Date,Math,JSON,Object,Array,RegExp,String,Number,console};
vm.runInNewContext(fs.readFileSync(path.join(root,'learning-continuity.js'),'utf8'),ctx,{filename:'learning-continuity.js'});
const tracker=ctx.window.MajickLearningContinuity;
assert(tracker,'Shared continuity tracker failed to register');
const item={course:'D772',skill:'mean',learningPathLessonId:'d772-s2-l4-1',prompt:'Which mean is correct for the classroom sample?',answer:'17'};
const prior=JSON.stringify(state.progress.D755)+JSON.stringify(state.progress.D756);
tracker.record({courseId:'D772',term:item.learningPathLessonId,correct:false,activity:'learninglab-guided',question:item});
tracker.record({courseId:'D772',term:item.learningPathLessonId,correct:false,activity:'study-now-independent',question:item});
tracker.record({courseId:'D772',term:item.learningPathLessonId,correct:false,activity:'game-realm-transfer',question:item});
let need=tracker.needs('D772').find(x=>x.lessonId===item.learningPathLessonId);
assert(need&&need.struggles===3);
assert(['learninglab-guided','study-now-independent','game-realm-transfer'].every(a=>need.activities.includes(a)),'All rooms must share the lesson-scoped need');
tracker.skillResult(item,false,false,'generated-lab-independent-formative');
tracker.skillResult(item,false,false,'game-realm');
tracker.skillResult(item,true,true,'guided');
const adaptive=state.progress.D772.adaptiveSkills[item.learningPathLessonId];
assert.equal(adaptive.status,'review-needed');
assert.equal(adaptive.masteryCertified,false);
assert.equal(adaptive.masteryEvidence.transferVerified,false);
assert.equal(tracker.masteryStatus(item.learningPathLessonId).certified,false);
assert.equal(JSON.stringify(state.progress.D755)+JSON.stringify(state.progress.D756),prior,'D755/D756 must not change');
state.activeCourse='D755';
assert.equal(tracker.skillResult(item,false,false,'game-realm'),null,'Other course cannot accept D772 question');
state.activeCourse='D772';
assert.equal(tracker.needs('D772')[0].lessonId,item.learningPathLessonId);
assert(saves>0,'New need must invoke the existing save path');
console.log('PASS D772 cross-room continuity: guided, Study Now, Game Realm, remediation, unearned mastery, course isolation and save calls');
