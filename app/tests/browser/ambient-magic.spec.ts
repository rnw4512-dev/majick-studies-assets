import { test, expect } from '@playwright/test'
for(const width of [390,820,1366]){
  test('foreground ambience is bounded, decorative, and respects both motion controls '+width,async({page})=>{
    await page.setViewportSize({width,height:900})
    await page.emulateMedia({reducedMotion:'no-preference'})
    await page.goto('/#/home')
    const ambient=page.locator('.ambient-scene')
    await expect(ambient).toHaveCount(1)
    await expect(ambient).toHaveAttribute('data-ambient','home')
    await expect(ambient).toHaveAttribute('aria-hidden','true')
    await expect(ambient).toHaveCSS('pointer-events','none')
    await expect(page.locator('.ambient-firefly')).toHaveCount(8)
    await expect(page.locator('.ambient-wisp')).toHaveCount(2)
    await expect(page.locator('.ambient-lantern')).toHaveCount(1)
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(11)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.getByRole('button',{name:'Reduce motion: Off'}).click()
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(0)
    await expect(page.locator('.ambient-firefly').first()).toBeVisible()
    await page.getByRole('button',{name:'Reduce motion: On'}).click()
    await page.emulateMedia({reducedMotion:'reduce'})
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(0)
    await page.emulateMedia({reducedMotion:'no-preference'})
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(11)
    if(width<=700)await page.getByRole('button',{name:'School rooms'}).click()
    await page.getByRole('navigation',{name:'School rooms'}).getByRole('link',{name:'Scholar’s Study Hall',exact:true}).click()
    await expect(page.getByRole('heading',{level:1})).toHaveText('Scholar’s Study Hall')
    await expect(ambient).toHaveAttribute('data-ambient','study')
    await expect(page.locator('.ambient-firefly')).toHaveCount(0)
    await expect(page.locator('.ambient-candle')).toHaveCount(3)
    await expect(page.locator('.ambient-quill')).toHaveCount(2)
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(8)
    expect(await page.locator('.magic-spark,.magic-poof').count()).toBeLessThanOrEqual(24)
    await expect(page.locator('.magic-poof')).toHaveCount(0)
    await page.getByRole('button',{name:'Reduce motion: Off'}).click()
    await expect.poll(()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(0)
    await page.getByRole('link',{name:'Return to Collegium'}).click()
    await expect(ambient).toHaveAttribute('data-ambient','home')
    await expect(page.locator('.magic-poof')).toHaveCount(0)
    await page.getByRole('link',{name:'Explore Learning Lab'}).click()
    await expect(ambient).toHaveCount(0)
  })
}
test('hidden-tab state cancels ambience and transient particles, then restores motion',async({page})=>{
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/')
  await page.evaluate(()=>{
    Object.defineProperty(document,'hidden',{configurable:true,get:()=>true})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(page.locator('.school')).toHaveClass(/magic-paused/)
  await expect.poll(()=>page.locator('.ambient-scene').evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(0)
  await expect(page.locator('.magic-spark,.magic-poof')).toHaveCount(0)
  await page.evaluate(()=>{
    Object.defineProperty(document,'hidden',{configurable:true,get:()=>false})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(page.locator('.school')).not.toHaveClass(/magic-paused/)
  await expect.poll(()=>page.locator('.ambient-scene').evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(11)
  await page.getByRole('link',{name:'Explore Learning Lab'}).click()
  await expect(page.locator('.magic-poof').first()).toBeAttached()
  await expect(page.locator('.magic-poof')).toHaveCount(0)
})
