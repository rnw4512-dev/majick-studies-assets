import { test, expect } from '@playwright/test'
for(const width of [390,820,1366]){
  test('living magic: image anchoring, bounded effects, motion and room isolation '+width,async({page})=>{
    await page.setViewportSize({width,height:900})
    await page.emulateMedia({reducedMotion:'no-preference'})
    await page.goto('/#/home')
    const ambient=page.locator('.ambient-scene')
    const count=(selector:string)=>page.locator(selector+':visible')
    const mobile=width<=700
    await expect(ambient).toHaveCount(1)
    await expect(ambient).toHaveAttribute('data-ambient','home')
    await expect(ambient).toHaveAttribute('aria-hidden','true')
    await expect(ambient).toHaveCSS('pointer-events','none')
    await expect(count('.ambient-firefly')).toHaveCount(mobile?8:14)
    await expect(count('.ambient-wisp')).toHaveCount(mobile?2:3)
    await expect(page.locator('.ambient-lantern')).toHaveCount(1)
    await expect(page.locator('.ambient-moonbeam')).toHaveCount(1)
    const delta=await page.locator('.ambient-lantern').evaluate(el=>{
      const image=document.querySelector<HTMLImageElement>('.scene-portrait img')!
      const b=image.getBoundingClientRect(),g=el.getBoundingClientRect()
      const scale=Math.max(b.width/image.naturalWidth,b.height/image.naturalHeight)
      const w=image.naturalWidth*scale,h=image.naturalHeight*scale
      const [x,y]=getComputedStyle(image).objectPosition.split(' ').map(s=>parseFloat(s)/100)
      return {x:Math.abs(g.left+g.width/2-(b.left+(b.width-w)*x+w*.13)),y:Math.abs(g.top+g.height/2-(b.top+(b.height-h)*y+h*.15))}
    })
    expect(delta.x).toBeLessThan(3)
    expect(delta.y).toBeLessThan(3)
    const moving=()=>ambient.evaluate(el=>el.getAnimations({subtree:true}).length)
    await expect.poll(moving).toBe(mobile?12:19)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.getByRole('button',{name:'Reduce motion: Off'}).click()
    await expect.poll(moving).toBe(0)
    await expect(count('.ambient-firefly').first()).toBeVisible()
    await page.getByRole('button',{name:'Reduce motion: On'}).click()
    await page.emulateMedia({reducedMotion:'reduce'})
    await expect.poll(moving).toBe(0)
    await page.emulateMedia({reducedMotion:'no-preference'})
    await expect.poll(moving).toBe(mobile?12:19)
    if(mobile)await page.getByRole('button',{name:'School rooms'}).click()
    await page.getByRole('navigation',{name:'School rooms'}).getByRole('link',{name:'Scholar’s Study Hall',exact:true}).click()
    await expect(page.getByRole('heading',{level:1})).toHaveText('Scholar’s Study Hall')
    await expect(ambient).toHaveAttribute('data-ambient','study')
    await expect(page.locator('.ambient-firefly')).toHaveCount(0)
    await expect(count('.ambient-candle')).toHaveCount(mobile?3:4)
    await expect(count('.ambient-quill')).toHaveCount(mobile?3:4)
    await expect(page.locator('.ambient-painted-candle')).toHaveCount(3)
    await expect.poll(moving).toBe(mobile?18:23)
    expect(await page.locator('.magic-spark,.magic-poof').count()).toBeLessThanOrEqual(24)
    await expect(page.locator('.magic-poof')).toHaveCount(0)
    await page.getByRole('button',{name:'Reduce motion: Off'}).click()
    await expect.poll(moving).toBe(0)
    await page.getByRole('link',{name:'Return to Collegium'}).click()
    await expect(ambient).toHaveAttribute('data-ambient','home')
    await expect(page.locator('.magic-poof')).toHaveCount(0)
    await page.getByRole('link',{name:'Explore Learning Lab'}).click()
    await expect(ambient).toHaveAttribute('data-ambient','learn')
    await expect(count('.ambient-mote')).toHaveCount(mobile?3:5)
    await expect.poll(moving).toBe(0)
  })
}
test('hidden-tab state cancels ambience and transient particles, then restores motion',async({page})=>{
  await page.setViewportSize({width:1366,height:900})
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/')
  await page.evaluate(()=>{
    Object.defineProperty(document,'hidden',{configurable:true,get:()=>true})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(page.locator('.school')).toHaveClass(/magic-paused/)
  await expect.poll(()=>page.locator('.ambient-scene').evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(0)
  await expect(page.locator('.magic-spark,.magic-poof')).toHaveCount(0)
  await page.evaluate(()=>{
    Object.defineProperty(document,'hidden',{configurable:true,get:()=>false})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(page.locator('.school')).not.toHaveClass(/magic-paused/)
  await expect.poll(()=>page.locator('.ambient-scene').evaluate(el=>el.getAnimations({subtree:true}).length)).toBe(19)
  await page.getByRole('link',{name:'Explore Learning Lab'}).click()
  await expect(page.locator('.magic-poof').first()).toBeAttached()
  await expect(page.locator('.magic-poof')).toHaveCount(0)
})
