import { test, expect } from '@playwright/test'
for (const width of [390,820,1366]) {
  test('shared magic supports navigation, focus, reduced motion and contrast at '+width,async({page})=>{
    await page.setViewportSize({width,height:900})
    await page.goto('/')
    const link=page.getByRole('link',{name:'Explore Learning Lab'})
    await link.hover()
    await expect(link).toHaveCSS('animation-name','magic-shimmer')
    await link.focus()
    await expect(link).toHaveCSS('animation-name','magic-shimmer')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading',{level:1})).toHaveText('Learning Lab')
    expect(await page.locator('.magic-spark').count()).toBeLessThanOrEqual(24)
    await expect(page.locator('.magic-sparks')).toHaveCSS('pointer-events','none')
    await expect(page.locator('.magic-spark')).toHaveCount(0)
    await page.getByRole('button',{name:'Reduce motion: Off'}).click()
    const back=page.getByRole('link',{name:'Return to Collegium'})
    await back.hover()
    await expect(back).toHaveCSS('animation-name','none')
    await expect(back.locator('.portal-arrow')).toHaveCSS('transform','none')
    await back.click()
    await expect(page.getByRole('heading',{level:1})).toHaveText('Moonlit Collegium')
    await expect(page.locator('.magic-spark')).toHaveCount(0)
    await page.getByRole('button',{name:'Reduce motion: On'}).click()
    await page.emulateMedia({reducedMotion:'reduce'})
    await link.hover()
    await expect(link).toHaveCSS('animation-name','none')
    await expect(link.locator('.arrow-spark')).toHaveCSS('animation-name','none')
    await link.click()
    await expect(page.getByRole('heading',{level:1})).toHaveText('Learning Lab')
    await expect(page.locator('.magic-spark')).toHaveCount(0)
    await page.getByRole('link',{name:'Backup practice'}).click()
    await expect(page.locator('nav [aria-current=page]')).toHaveCount(0)
    await page.getByRole('button',{name:'Open backup practice'}).click()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    const ratio=await page.locator('.paper').evaluate(el=>{
      const s=getComputedStyle(el)
      const luminance=(color:string)=>{
        const rgb=color.match(/[\d.]+/g)!.slice(0,3).map(Number).map(x=>x/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4)
        return .2126*rgb[0]+.7152*rgb[1]+.0722*rgb[2]
      }
      const l=[luminance(s.color),luminance(s.backgroundColor)].sort((a,b)=>b-a)
      return (l[0]+.05)/(l[1]+.05)
    })
    expect(ratio).toBeGreaterThanOrEqual(4.5)
    await page.getByRole('link',{name:'Storage safety check'}).click()
    await expect(page.locator('nav [aria-current=page]')).toHaveCount(0)
  })
}
test('trusted presses produce bounded sparks and clean up',async({page})=>{
  await page.goto('/')
  const toggle=page.getByRole('button',{name:'Reduce motion: Off'})
  // Use a native same-page link that stays in the document after activation.
  const link=page.getByRole('link',{name:'Explore Learning Lab'})
  await link.click()
  await expect(page.locator('.magic-spark').first()).toBeAttached()
  expect(await page.locator('.magic-spark').count()).toBeLessThanOrEqual(24)
  await toggle.click()
  await expect(page.locator('.magic-spark')).toHaveCount(0)
})
